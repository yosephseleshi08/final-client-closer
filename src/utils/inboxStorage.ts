export const INBOX_STORAGE_KEY = 'outreach_engine_lead_inbox_v1';

/**
 * Loads pending leads currently sitting in the Lead Inbox from localStorage.
 */
export function loadInboxLeads(): InboxLead[] {
  try {
    const raw = localStorage.getItem(INBOX_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed)) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Failed to load lead inbox from localStorage:', err);
  }
  return [];
}

/**
 * Persists the Inbox leads list and dispatches an event so all UI components update.
 */
export function saveInboxLeads(leads: InboxLead[]): void {
  try {
    localStorage.setItem(INBOX_STORAGE_KEY, JSON.stringify(leads));
    window.dispatchEvent(new CustomEvent('inbox_leads_changed', { detail: leads }));
  } catch (err) {
    console.error('Failed to save lead inbox to localStorage:', err);
  }
}

/**
 * Removes a lead from the inbox list by ID.
 */
export function removeInboxLead(id: string): InboxLead[] {
  const current = loadInboxLeads();
  const updated = current.filter((l) => l.id !== id);
  saveInboxLeads(updated);
  return updated;
}

/**
 * Clears all items in the inbox.
 */
export function clearAllInboxLeads(): void {
  saveInboxLeads([]);
}

/**
 * Safely extracts the raw platform link / handle / URL directly from a lead JSON object.
 * CRITICAL RULE:
 * 1. Never mutate, strip underscores, remove special characters, or append words.
 * 2. Return the exact raw value from the JSON.
 * 3. Supports all standard and alternative keys (platformLink, platform_link, Platform Link, handle, etc.).
 * 4. Never lets an empty string "" in one key block finding a valid value in another key.
 */
export function extractRawPlatformLink(it: any): string {
  if (!it || typeof it !== 'object') return '';

  const priorityKeys = [
    'platformLink',
    'platform_link',
    'Platform Link',
    'PlatformLink',
    'profileLink',
    'profile_link',
    'Profile Link',
    'ProfileLink',
    'handle',
    'Handle',
    'instagram_handle',
    'instagramHandle',
    'Instagram Handle',
    'ig_handle',
    'igHandle',
    'IG Handle',
    'url',
    'Url',
    'profileUrl',
    'profile_url',
    'Profile Url',
    'link',
    'Link',
    'instagram',
    'Instagram',
    'facebook',
    'Facebook',
    'email',
    'Email',
  ];

  // Pass 1: Check known keys with non-empty string values
  for (const key of priorityKeys) {
    if (it[key] !== undefined && it[key] !== null) {
      const val = String(it[key]).trim();
      if (val !== '') {
        return val;
      }
    }
  }

  // Pass 2: Case-insensitive and normalized key matching across all object properties
  const objKeys = Object.keys(it);
  for (const priority of priorityKeys) {
    const normPriority = priority.toLowerCase().replace(/[\s_-]+/g, '');
    const matchedKey = objKeys.find(
      (k) => k.toLowerCase().replace(/[\s_-]+/g, '') === normPriority
    );
    if (matchedKey && it[matchedKey] !== undefined && it[matchedKey] !== null) {
      const val = String(it[matchedKey]).trim();
      if (val !== '') {
        return val;
      }
    }
  }

  // Pass 3: Inspect nested objects if present (e.g. it.lead, it.details, it.prospect, it.info)
  const nestedKeys = ['lead', 'details', 'prospect', 'leadDetails', 'info', 'data'];
  for (const nestedKey of nestedKeys) {
    if (it[nestedKey] && typeof it[nestedKey] === 'object') {
      const nestedVal = extractRawPlatformLink(it[nestedKey]);
      if (nestedVal) {
        return nestedVal;
      }
    }
  }

  return '';
}

/**
 * Parses the raw text of qualified-leads.json file generated by Lead Engine.
 * Supports arrays or wrapped objects with flexible key naming.
 */
export function parseQualifiedLeadsJson(jsonText: string): InboxLead[] {
  const cleanedText = String(jsonText || '').replace(/^\uFEFF/, '').trim();
  if (!cleanedText) {
    throw new Error('The uploaded file is empty.');
  }

  let parsed: any;
  try {
    parsed = JSON.parse(cleanedText);
  } catch {
    // Fallback for NDJSON (one JSON object per line)
    const lines = cleanedText
      .split(/\r?\n/)
      .map((l) => l.trim())
      .filter(Boolean);
    const lineObjects: any[] = [];
    for (const line of lines) {
      try {
        const obj = JSON.parse(line);
        if (obj && typeof obj === 'object') lineObjects.push(obj);
      } catch {
        // ignore invalid line
      }
    }
    if (lineObjects.length > 0) {
      parsed = lineObjects;
    } else {
      throw new Error('Invalid JSON format. Please ensure qualified-leads.json contains valid JSON syntax.');
    }
  }

  let items: any[] = [];
  if (Array.isArray(parsed)) {
    items = parsed;
  } else if (parsed && typeof parsed === 'object') {
    const arrayKey = [
      'leads',
      'qualifiedLeads',
      'qualified_leads',
      'data',
      'results',
      'items',
      'prospects',
      'rows',
      'restaurants',
    ].find((k) => Array.isArray(parsed[k]));

    if (arrayKey) {
      items = parsed[arrayKey];
    } else if (
      Array.isArray(parsed.instagram) ||
      Array.isArray(parsed.facebook) ||
      Array.isArray(parsed.email) ||
      Array.isArray(parsed.combined) ||
      Array.isArray(parsed.ig) ||
      Array.isArray(parsed.fb)
    ) {
      const tagged = (arr: any[], defaultPlat: string) =>
        Array.isArray(arr)
          ? arr.map((x) => (x && typeof x === 'object' ? { platform: defaultPlat, ...x } : x))
          : [];
      items = [
        ...tagged(parsed.instagram, 'Instagram'),
        ...tagged(parsed.ig, 'Instagram'),
        ...tagged(parsed.facebook, 'Facebook'),
        ...tagged(parsed.fb, 'Facebook'),
        ...tagged(parsed.email, 'Email'),
        ...tagged(parsed.combined, 'Email'),
      ];
    } else {
      // Single lead object fallback
      items = [parsed];
    }
  }

  const result: InboxLead[] = [];
  const nowIso = new Date().toISOString();

  for (let i = 0; i < items.length; i++) {
    const it = items[i];
    if (!it || typeof it !== 'object') continue;

    const rawPlatformLink = extractRawPlatformLink(it);

    const name = String(
      it.name ||
        it.restaurantName ||
        it.restaurant ||
        it.businessName ||
        it.business_name ||
        it.leadName ||
        it.title ||
        it.company ||
        it.companyName ||
        it.accountName ||
        it.handle ||
        `Lead #${i + 1}`
    ).trim();

    const explicitRawPlatform = String(
      it.platform || it.channel || it.source || it.platformName || ''
    ).trim();

    const lowerPlatform = explicitRawPlatform.toLowerCase();
    let platform: 'Instagram' | 'Facebook' | 'Email' | 'Other' = 'Instagram';
    let rawPlatform = explicitRawPlatform || 'IG';

    if (lowerPlatform.includes('fb') || lowerPlatform.includes('face')) {
      platform = 'Facebook';
    } else if (lowerPlatform.includes('email') || lowerPlatform.includes('mail')) {
      platform = 'Email';
    } else if (lowerPlatform.includes('ig') || lowerPlatform.includes('insta')) {
      platform = 'Instagram';
    } else {
      // Infer platform from link/contact fields when explicit platform is missing or generic
      const linkLower = rawPlatformLink.toLowerCase();
      if (
        linkLower.startsWith('mailto:') ||
        (linkLower.includes('@') && !linkLower.includes('instagram.com') && !linkLower.includes('facebook.com') && !linkLower.startsWith('@')) ||
        Boolean(it.email || it.Email || it.emailAddress || it.contactEmail)
      ) {
        platform = 'Email';
        rawPlatform = explicitRawPlatform || 'Email';
      } else if (
        linkLower.includes('facebook.com') ||
        linkLower.includes('fb.com') ||
        linkLower.includes('fb.me') ||
        Boolean(it.facebook || it.Facebook || it.facebookUrl)
      ) {
        platform = 'Facebook';
        rawPlatform = explicitRawPlatform || 'FB';
      } else {
        platform = 'Instagram';
      }
    }

    // Explicit dual-channel link extraction
    const rawFb = String(
      it.facebook ||
        it.Facebook ||
        it.facebookUrl ||
        it.facebook_url ||
        it.facebookLink ||
        it.facebook_link ||
        it.fb ||
        it.socialLinks?.facebook ||
        (rawPlatformLink.toLowerCase().includes('facebook.com') || rawPlatformLink.toLowerCase().includes('fb.com')
          ? rawPlatformLink
          : '')
    ).trim();

    const rawEmail = String(
      it.email ||
        it.Email ||
        it.emailAddress ||
        it.email_address ||
        it.contactEmail ||
        it.contact_email ||
        it.socialLinks?.email ||
        (rawPlatformLink.includes('@') &&
        !rawPlatformLink.toLowerCase().includes('facebook.com') &&
        !rawPlatformLink.toLowerCase().includes('instagram.com') &&
        !rawPlatformLink.trim().startsWith('@')
          ? rawPlatformLink.replace(/^mailto:/i, '')
          : '')
    ).trim();

    const prompt = String(
      it.prompt ||
        it.customPitch ||
        it.pitch ||
        it.pitchHook ||
        it.leadAnalysis ||
        it.outreachPrompt ||
        it.notes ||
        ''
    ).trim();

    result.push({
      id: `inbox-${Date.now()}-${i}-${Math.random().toString(36).substring(2, 8)}`,
      name: name || 'Qualified Prospect',
      platform,
      rawPlatform,
      profileLink: rawPlatformLink,
      platformLink: rawPlatformLink,
      facebook: rawFb || undefined,
      email: rawEmail || undefined,
      prompt,
      uploadedAt: nowIso,
      rawDetails: it,
    });
  }

  return result;
}

/**
 * Accepts an inbox lead:
 * 1. Resolves channel (Instagram or Facebook or Email)
 * 2. Generates ID (e.g. IG-X, FB-Y)
 * 3. Saves prompt into customPitch, prompt, and leadAnalysis
 * 4. Adds lead to CRM channel storage at index 0
 * 5. Removes the lead from inbox
 */
export function acceptInboxLeadIntoCrm(
  lead: InboxLead,
  existingChannelLeads?: {
    combined?: ChannelLead[];
    instagram?: ChannelLead[];
    facebook?: ChannelLead[];
    email?: ChannelLead[];
  },
  options?: { forceAccept?: boolean }
): {
  targetChannel: MultiChannelType;
  newLead: ChannelLead;
  updatedLeads: ChannelLead[];
  isDuplicate?: boolean;
  duplicateReason?: string;
} {
  let targetChannel: MultiChannelType = 'instagram';
  if (lead.platform === 'Facebook' || lead.platform === 'Email') {
    targetChannel = 'combined';
  } else {
    targetChannel = 'instagram';
  }

  // Always prefer fresh persisted channel storage so stale UI props never overwrite or drop leads
  const storedCombined = loadChannelLeads('combined');
  const storedInstagram = loadChannelLeads('instagram');
  const combinedListForDup = storedCombined.length > 0 ? storedCombined : (existingChannelLeads?.combined ?? []);
  const igListForDup = storedInstagram.length > 0 ? storedInstagram : (existingChannelLeads?.instagram ?? []);
  const currentLeads = targetChannel === 'combined' ? combinedListForDup : igListForDup;

  // CRITICAL RULE: Never modify the platformLink value on import.
  const rawPlatformLink =
    (typeof lead.platformLink === 'string' && lead.platformLink.trim()) ||
    (typeof lead.profileLink === 'string' && lead.profileLink.trim()) ||
    extractRawPlatformLink(lead.rawDetails) ||
    '';

  const storedLink = rawPlatformLink;

  if (!options?.forceAccept) {
    // Channel-scoped normalized duplicate guard across link, active CRM, Backstage archive, and immutable dispatchLog
    const normalizedMatch = findNormalizedDuplicateMatches(
      {
        name: lead.name,
        link: storedLink,
        platformLink: storedLink,
        email: lead.email,
        facebook: lead.facebook,
        instagram: lead.instagram,
      },
      {
        targetChannel: targetChannel === 'combined' ? 'combined' : 'instagram',
        activeCombined: combinedListForDup,
        activeInstagram: igListForDup,
      }
    );

    if (normalizedMatch.hasMatch) {
      // Automatically reject & remove duplicate lead from Inbox
      removeInboxLead(lead.id);
      return {
        targetChannel,
        newLead: normalizedMatch.bestMatch || currentLeads[0],
        updatedLeads: currentLeads,
        isDuplicate: true,
        duplicateReason:
          normalizedMatch.summaryReason ||
          `Matches existing or previously dispatched lead "${lead.name}"`,
      };
    }

    if (storedLink) {
      const duplicate = findDuplicateLead(storedLink, currentLeads);
      if (duplicate) {
        // Automatically reject & remove duplicate-link lead from Inbox
        removeInboxLead(lead.id);
        return {
          targetChannel,
          newLead: duplicate,
          updatedLeads: currentLeads,
          isDuplicate: true,
          duplicateReason: `Link already exists on ${duplicate.id} (${duplicate.name})`,
        };
      }
    }
  }

  const { id, numericId } = getNextLeadId(targetChannel, currentLeads);
  const nowIso = new Date().toISOString();
  const isFbRestricted = Boolean(lead.rawDetails?.fb_message_restricted || lead.rawDetails?.restricted);

  // Strictly enforce daily quota (IG: 6, Combined: 4) & skip Sunday
  const assignedScheduleDate = getNextAvailableScheduleDate(currentLeads, targetChannel);

  // Dual-channel link extraction (Facebook & Email)
  const extractedFb =
    lead.facebook ||
    lead.rawDetails?.facebook ||
    lead.rawDetails?.Facebook ||
    lead.rawDetails?.facebookUrl ||
    lead.rawDetails?.facebook_url ||
    lead.rawDetails?.fb ||
    lead.rawDetails?.socialLinks?.facebook ||
    (rawPlatformLink.includes('facebook.com') || rawPlatformLink.includes('fb.com') ? rawPlatformLink : undefined);

  const extractedEmail =
    lead.email ||
    lead.rawDetails?.email ||
    lead.rawDetails?.Email ||
    lead.rawDetails?.emailAddress ||
    lead.rawDetails?.contactEmail ||
    lead.rawDetails?.socialLinks?.email ||
    (rawPlatformLink.includes('@') && !rawPlatformLink.includes('facebook.com') && !rawPlatformLink.includes('instagram.com') ? rawPlatformLink : undefined);

  const emailOnly = !hasSocialWarmupLink({
    channel: targetChannel,
    link: storedLink,
    platformLink: storedLink,
    facebook: extractedFb || undefined,
    rawDetails: lead.rawDetails,
  });

  const newChannelLead: ChannelLead = {
    id,
    numericId,
    name: lead.name,
    link: storedLink,
    platformLink: storedLink,
    facebook: extractedFb || undefined,
    email: extractedEmail || undefined,
    channel: targetChannel,
    voiceType: getStrictVoiceTypeForId(numericId, targetChannel),
    isVoiceTypeOverridden: false,
    sortOrder: 0,
    createdAt: nowIso,
    scheduledDate: assignedScheduleDate,
    warmupStatus: emailOnly ? 'warmed' : 'locked',
    isWarmedUp: emailOnly,
    // Save prompt & analysis to lead data as requested (prompts untouched)
    prompt: lead.prompt || undefined,
    leadAnalysis: lead.prompt || undefined,
    analysisSavedAt: lead.prompt ? nowIso : undefined,
    // 4-step sequence messages start empty until operator writes them:
    initialDM: '',
    customPitch: '',
    stagedDmMiniPitch: '',
    followupDM_Day4: '',
    followupDM_Day7: '',
    followup3DM: '',
    followupDM_Day8: '',
    followupDM_Day14: '',
    followup7DM: '',
    breakupDM_Day14: '',
    breakupDM_Day30: '',
    isSequenceConfigured: false,
    rawDetails: lead.rawDetails,
  };

  // Keep leads ordered by numericId ascending, align sortOrder, and recalculate ALL voice types strictly by ID
  const orderedLeads = [...currentLeads, newChannelLead].sort(
    (a, b) => (a.numericId ?? 0) - (b.numericId ?? 0)
  );
  const updatedLeads = recalculateAllVoiceTypes(
    orderedLeads.map((l, index) => ({
      ...l,
      sortOrder: index,
    })),
    targetChannel
  );

  // Save to persistent channel storage
  saveChannelLeads(targetChannel, updatedLeads);

  // Remove from Inbox
  removeInboxLead(lead.id);

  const savedNewLead = updatedLeads.find((l) => l.id === newChannelLead.id) || newChannelLead;

  return {
    targetChannel,
    newLead: savedNewLead,
    updatedLeads,
    isDuplicate: false,
  };
}

/**
 * Batch Accepts All Pending Leads from Inbox into CRM:
 * 1. Iterates through all inbox leads.
 * 2. Determines target channel ('instagram' or 'combined' for FB/Email).
 * 3. Assigns IDs and auto-scheduled dates based on quotas (IG: 6, Combined: 4) skipping Sundays.
 * 4. Checks duplicates to avoid duplicating any lead already in pipeline or already added in batch.
 * 5. Saves to persistent storage for both channels.
 * 6. Clears the inbox completely.
 * 7. Returns updated leads for combined and instagram channels, along with acceptedCount and duplicateCount.
 */
export function acceptAllInboxLeadsIntoCrm(
  leadsToAccept: InboxLead[],
  existingChannelLeads?: {
    combined?: ChannelLead[];
    instagram?: ChannelLead[];
  }
): {
  updatedCombined: ChannelLead[];
  updatedInstagram: ChannelLead[];
  acceptedCount: number;
  duplicateCount: number;
  remainingLeads: InboxLead[];
  skippedLeads: Array<{ lead: InboxLead; reason: string }>;
} {
  // Always read authoritative localStorage state first so stale props cannot drop existing leads
  const storedCombined = loadChannelLeads('combined');
  const storedInstagram = loadChannelLeads('instagram');
  let combinedList = [...(storedCombined.length > 0 ? storedCombined : (existingChannelLeads?.combined ?? []))];
  let instagramList = [...(storedInstagram.length > 0 ? storedInstagram : (existingChannelLeads?.instagram ?? []))];

  let acceptedCount = 0;
  let duplicateCount = 0;
  let addedToCombined = 0;
  let addedToInstagram = 0;
  const acceptedInboxIds = new Set<string>();
  const skippedLeads: Array<{ lead: InboxLead; reason: string }> = [];
  const nowIso = new Date().toISOString();

  for (const lead of leadsToAccept) {
    let targetChannel: MultiChannelType = 'instagram';
    if (lead.platform === 'Facebook' || lead.platform === 'Email') {
      targetChannel = 'combined';
    } else {
      targetChannel = 'instagram';
    }

    const currentTargetList = targetChannel === 'combined' ? combinedList : instagramList;
    const channelScope = targetChannel === 'combined' ? 'combined' : 'instagram';

    const rawPlatformLink =
      (typeof lead.platformLink === 'string' && lead.platformLink.trim()) ||
      (typeof lead.profileLink === 'string' && lead.profileLink.trim()) ||
      extractRawPlatformLink(lead.rawDetails) ||
      '';

    const storedLink = rawPlatformLink;

    const normMatch = findNormalizedDuplicateMatches(
      {
        name: lead.name,
        link: storedLink,
        platformLink: storedLink,
        email: lead.email,
        facebook: lead.facebook,
        instagram: lead.instagram,
      },
      {
        targetChannel: channelScope,
        activeCombined: combinedList,
        activeInstagram: instagramList,
      }
    );

    const histDate = !storedLink && !lead.email && !lead.facebook && !lead.instagram
      ? getHistoricalSentDateForName(lead.name, channelScope)
      : null;

    if (normMatch.hasMatch || histDate) {
      duplicateCount++;
      skippedLeads.push({
        lead,
        reason:
          normMatch.summaryReason ||
          `Previously dispatched as "${lead.name}" (${histDate})`,
      });
      continue;
    }

    if (storedLink) {
      const duplicate = findDuplicateLead(storedLink, currentTargetList);
      if (duplicate) {
        duplicateCount++;
        skippedLeads.push({
          lead,
          reason: `Link already exists on ${duplicate.id} (${duplicate.name})`,
        });
        continue;
      }
    }

    const { id, numericId } = getNextLeadId(targetChannel, currentTargetList);
    const assignedScheduleDate = getNextAvailableScheduleDate(currentTargetList, targetChannel);

    const extractedFb =
      lead.facebook ||
      lead.rawDetails?.facebook ||
      lead.rawDetails?.Facebook ||
      lead.rawDetails?.facebookUrl ||
      lead.rawDetails?.facebook_url ||
      lead.rawDetails?.fb ||
      lead.rawDetails?.socialLinks?.facebook ||
      (rawPlatformLink.toLowerCase().includes('facebook.com') || rawPlatformLink.toLowerCase().includes('fb.com')
        ? rawPlatformLink
        : undefined);

    const extractedEmail =
      lead.email ||
      lead.rawDetails?.email ||
      lead.rawDetails?.Email ||
      lead.rawDetails?.emailAddress ||
      lead.rawDetails?.contactEmail ||
      lead.rawDetails?.socialLinks?.email ||
      (rawPlatformLink.includes('@') &&
      !rawPlatformLink.toLowerCase().includes('facebook.com') &&
      !rawPlatformLink.toLowerCase().includes('instagram.com') &&
      !rawPlatformLink.trim().startsWith('@')
        ? rawPlatformLink.replace(/^mailto:/i, '')
        : undefined);

    const emailOnly = !hasSocialWarmupLink({
      channel: targetChannel,
      link: storedLink,
      platformLink: storedLink,
      facebook: extractedFb || undefined,
      rawDetails: lead.rawDetails,
    });

    const newChannelLead: ChannelLead = {
      id,
      numericId,
      name: lead.name,
      link: storedLink,
      platformLink: storedLink,
      facebook: extractedFb || undefined,
      email: extractedEmail || undefined,
      channel: targetChannel,
      voiceType: getStrictVoiceTypeForId(numericId, targetChannel),
      isVoiceTypeOverridden: false,
      sortOrder: currentTargetList.length,
      createdAt: nowIso,
      scheduledDate: assignedScheduleDate,
      warmupStatus: emailOnly ? 'warmed' : 'locked',
      isWarmedUp: emailOnly,
      prompt: lead.prompt || undefined,
      leadAnalysis: lead.prompt || undefined,
      analysisSavedAt: lead.prompt ? nowIso : undefined,
      initialDM: '',
      customPitch: '',
      stagedDmMiniPitch: '',
      followupDM_Day4: '',
      followupDM_Day7: '',
      followup3DM: '',
      followupDM_Day8: '',
      followupDM_Day14: '',
      followup7DM: '',
      breakupDM_Day14: '',
      breakupDM_Day30: '',
      isSequenceConfigured: false,
      rawDetails: lead.rawDetails,
    };

    if (targetChannel === 'combined') {
      combinedList.push(newChannelLead);
      addedToCombined++;
    } else {
      instagramList.push(newChannelLead);
      addedToInstagram++;
    }
    acceptedInboxIds.add(lead.id);
    acceptedCount++;
  }

  // Only recalculate voice types and persist channels that actually received new leads
  if (addedToCombined > 0) {
    combinedList = recalculateAllVoiceTypes(
      [...combinedList]
        .sort((a, b) => (a.numericId ?? 0) - (b.numericId ?? 0))
        .map((l, idx) => ({ ...l, sortOrder: idx })),
      'combined'
    );
    saveChannelLeads('combined', combinedList);
  }
  if (addedToInstagram > 0) {
    instagramList = recalculateAllVoiceTypes(
      instagramList.map((l, idx) => ({ ...l, sortOrder: idx })),
      'instagram'
    );
    saveChannelLeads('instagram', instagramList);
  }

  // Remove both accepted leads AND auto-rejected duplicate-link leads from Inbox so duplicates disappear
  const currentInbox = loadInboxLeads();
  const autoRejectedIds = new Set(skippedLeads.map((s) => s.lead.id));
  const remainingLeads = currentInbox.filter(
    (l) => !acceptedInboxIds.has(l.id) && !autoRejectedIds.has(l.id)
  );
  saveInboxLeads(remainingLeads);

  return {
    updatedCombined: combinedList,
    updatedInstagram: instagramList,
    acceptedCount,
    duplicateCount,
    remainingLeads,
    skippedLeads,
  };
}
